## 📌 Project Overview

This project presents an interactive Human Resource Analytics Dashboard developed using Tableau. The dashboard provides insights into workforce demographics, employee attrition, departmental performance, salary distribution, and workforce trends.

The dashboard enables HR professionals and business stakeholders to make data-driven decisions through interactive visualizations and filtering capabilities.

---

## 🎯 Business Objectives

- Analyze employee demographics.
- Monitor hiring and attrition trends.
- Evaluate department performance.
- Explore salary distribution patterns.
- Identify workforce characteristics by age, gender, and education.
- Support strategic HR decision-making.

